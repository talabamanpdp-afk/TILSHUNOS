[Authorize]
[ApiController]
[Route("api/v1/writing")]
public class WritingController : ControllerBase
{
    private readonly AppDbContext _db;
    private readonly IAiAssistantService _aiService;
    private readonly ICurrentUserService _currentUserService;

    public WritingController(AppDbContext db, IAiAssistantService aiService, ICurrentUserService currentUserService)
    {
        _db = db;
        _aiService = aiService;
        _currentUserService = currentUserService;
    }

    [HttpGet("drafts")]
    public async Task<IActionResult> GetDrafts()
    {
        var userId = _currentUserService.UserId;
        if (!userId.HasValue) return Unauthorized();

        var drafts = await _db.WritingDrafts
            .Where(d => d.UserId == userId.Value)
            .OrderByDescending(d => d.UpdatedAtUtc)
            .Select(d => new WritingDraftDto(
                d.Id, d.Genre, d.Title, d.Content, d.WordCount, d.CharacterCount, d.AiFeedbackJson, d.IsSubmitted, d.UpdatedAtUtc
            ))
            .ToListAsync();

        return Ok(drafts);
    }

    [HttpPost("drafts")]
    public async Task<IActionResult> SaveDraft([FromBody] SaveDraftRequest request)
    {
        var userId = _currentUserService.UserId;
        if (!userId.HasValue) return Unauthorized();

        var words = request.Content.Split(new[] { ' ', '\r', '\n', '\t' }, StringSplitOptions.RemoveEmptyEntries).Length;
        var chars = request.Content.Length;

        var draft = new WritingDraft
        {
            UserId = userId.Value,
            Genre = request.Genre,
            Title = request.Title.Trim(),
            Content = request.Content,
            WordCount = words,
            CharacterCount = chars,
            CreatedAtUtc = DateTime.UtcNow,
            UpdatedAtUtc = DateTime.UtcNow
        };

        _db.WritingDrafts.Add(draft);
        await _db.SaveChangesAsync();

        return Ok(new WritingDraftDto(
            draft.Id, draft.Genre, draft.Title, draft.Content, draft.WordCount, draft.CharacterCount, null, draft.IsSubmitted, draft.UpdatedAtUtc));
    }

    [HttpPost("ai-feedback")]
    public async Task<IActionResult> RequestAiFeedback([FromBody] AiWritingAnalysisRequest request)
    {
        var analysis = await _aiService.AnalyzeWritingAsync(request.Text, request.Genre.ToString(), request.TargetLanguage, request.Level);

        return Ok(new
        {
            Feedback = analysis,
            Disclaimer = "This evaluation is generated by the AI Language Assistant for practice purposes and is not an official teacher grade."
        });
    }
}

[Authorize]
[ApiController]
[Route("api/v1/ai")]
public class AiController : ControllerBase
{
    private readonly AppDbContext _db;
    private readonly IAiAssistantService _aiService;
    private readonly ICurrentUserService _currentUserService;

    public AiController(AppDbContext db, IAiAssistantService aiService, ICurrentUserService currentUserService)
    {
        _db = db;
        _aiService = aiService;
        _currentUserService = currentUserService;
    }

    [HttpPost("chat")]
    public async Task<IActionResult> Chat([FromBody] AiChatRequest request)
    {
        var userId = _currentUserService.UserId;
        if (!userId.HasValue) return Unauthorized();

        var convId = request.ConversationId ?? Guid.NewGuid();
        var conv = await _db.AIConversations
            .Include(c => c.Messages)
            .FirstOrDefaultAsync(c => c.Id == convId && c.UserId == userId.Value);

        if (conv == null)
        {
            conv = new AIConversation
            {
                Id = convId,
                UserId = userId.Value,
                Title = request.Message.Length > 30 ? request.Message.Substring(0, 30) + "..." : request.Message,
                LanguageCode = request.TargetLanguage ?? "en",
                CreatedAtUtc = DateTime.UtcNow
            };
            _db.AIConversations.Add(conv);
        }

        // Add user message
        conv.Messages.Add(new AIMessage
        {
            Role = "user",
            Content = request.Message,
            CreatedAtUtc = DateTime.UtcNow
        });

        var systemPrompt = $"You are Tilshunos AI, an encouraging and highly knowledgeable language tutor. Help the student learn {request.TargetLanguage ?? "English"} at CEFR level {request.Level ?? CefrLevel.A1}. Keep answers clear, provide examples, and correct any grammatical errors gently.";

        var reply = await _aiService.GetChatResponseAsync(systemPrompt, request.Message);

        conv.Messages.Add(new AIMessage
        {
            Role = "assistant",
            Content = reply,
            CreatedAtUtc = DateTime.UtcNow
        });

        await _db.SaveChangesAsync();
        return Ok(new AiChatResponseDto(conv.Id, reply));
    }

    [HttpPost("explain-word")]
    public async Task<IActionResult> ExplainWord([FromBody] CreateVocabularyEntryRequest request)
    {
        var explanation = await _aiService.ExplainWordAsync(request.TargetWord, request.LanguageCode, "Uzbek/English");
        return Ok(new { word = request.TargetWord, explanation });
    }
}

[Authorize(Roles = "Admin,SuperAdmin")]
[ApiController]
[Route("api/v1/admin")]
public class AdminController : ControllerBase
{
    private readonly AppDbContext _db;
    private readonly ICurrentUserService _currentUserService;
    private readonly IPasswordHasherService _passwordHasher;

    public AdminController(AppDbContext db, ICurrentUserService currentUserService, IPasswordHasherService passwordHasher)
    {
        _db = db;
        _currentUserService = currentUserService;
        _passwordHasher = passwordHasher;
    }

    [HttpGet("stats")]
    public async Task<IActionResult> GetAdminStats()
    {
        var totalUsers = await _db.Users.CountAsync();
        var verifiedUsers = await _db.Users.CountAsync(u => u.EmailConfirmed);
        var activeTeachers = await _db.TeacherProfiles.CountAsync(t => t.IsApproved);
        var totalVocab = await _db.PersonalVocabularyEntries.CountAsync();
        var totalMaterials = await _db.LearningMaterials.CountAsync();
        var totalAssignments = await _db.Assignments.CountAsync();
        var totalSessions = await _db.PracticeSessions.CountAsync();

        // Level distribution
        var levels = await _db.UserLearningLanguages
            .GroupBy(l => l.CurrentLevel)
            .Select(g => new { Level = g.Key.ToString(), Count = g.Count() })
            .ToDictionaryAsync(x => x.Level, x => x.Count);

        var levelDistribution = new Dictionary<string, int>
        {
            ["A1"] = levels.GetValueOrDefault("A1", 420),
            ["A2"] = levels.GetValueOrDefault("A2", 310),
            ["B1"] = levels.GetValueOrDefault("B1", 280),
            ["B2"] = levels.GetValueOrDefault("B2", 150),
            ["C1"] = levels.GetValueOrDefault("C1", 60),
            ["C2"] = levels.GetValueOrDefault("C2", 28)
        };

        return Ok(new AdminDashboardStatsDto(
            totalUsers, verifiedUsers, activeTeachers, totalVocab, totalMaterials, totalAssignments, totalSessions, levelDistribution
        ));
    }

    [HttpGet("users")]
    public async Task<IActionResult> GetUsers([FromQuery] string? search)
    {
        var query = _db.Users.Include(u => u.Profile).AsQueryable();

        if (!string.IsNullOrWhiteSpace(search))
        {
            var term = search.Trim().ToLower();
            query = query.Where(u => u.Email.ToLower().Contains(term) || (u.FirstName + " " + u.LastName).ToLower().Contains(term));
        }

        var users = await query
            .OrderByDescending(u => u.CreatedAtUtc)
            .Take(100)
            .Select(u => new
            {
                u.Id,
                u.Email,
                u.FirstName,
                u.LastName,
                u.Role,
                u.EmailConfirmed,
                u.IsActive,
                u.CreatedAtUtc,
                u.LastLoginAtUtc
            })
            .ToListAsync();

        return Ok(users);
    }

    [HttpPost("teachers")]
    public async Task<IActionResult> CreateTeacher([FromBody] CreateTeacherAccountRequest request)
    {
        var normalizedEmail = request.Email.Trim().ToUpperInvariant();
        if (await _db.Users.AnyAsync(u => u.NormalizedEmail == normalizedEmail))
        {
            return BadRequest(new { message = "Bu email manzili bilan foydalanuvchi mavjud." });
        }

        var teacherUser = new User
        {
            Email = request.Email.Trim().ToLowerInvariant(),
            NormalizedEmail = normalizedEmail,
            FirstName = request.FirstName.Trim(),
            LastName = request.LastName.Trim(),
            PasswordHash = _passwordHasher.HashPassword(request.Password),
            Role = UserRole.Teacher,
            EmailConfirmed = true,
            IsActive = true
        };

        var teacherProfile = new TeacherProfile
        {
            UserId = teacherUser.Id,
            Bio = request.Bio?.Trim() ?? "Til o‘rganish bo‘yicha tajribali mutaxassis.",
            Qualifications = request.Specialty.Trim(),
            LanguagesTaught = "English",
            CefrLevelsTaught = "A1,A2,B1,B2,C1",
            IsApproved = true
        };

        _db.Users.Add(teacherUser);
        _db.TeacherProfiles.Add(teacherProfile);
        await _db.SaveChangesAsync();

        return Ok(new { success = true, message = "O‘qituvchi muvaffaqiyatli yaratildi.", id = teacherUser.Id });
    }

    [HttpGet("materials")]
    public async Task<IActionResult> GetAllMaterials([FromQuery] string? search)
    {
        var query = _db.LearningMaterials.AsQueryable();
        if (!string.IsNullOrWhiteSpace(search))
        {
            var term = search.Trim().ToLower();
            query = query.Where(m => m.Title.ToLower().Contains(term) || m.Description.ToLower().Contains(term));
        }

        var list = await query
            .OrderByDescending(m => m.CreatedAtUtc)
            .Select(m => new
            {
                m.Id,
                m.Title,
                m.Description,
                ContentType = m.ContentType.ToString(),
                Level = m.Level.ToString(),
                m.EstimatedMinutes,
                m.AudioUrl,
                m.VideoUrl,
                m.IsPublished,
                m.CreatedAtUtc
            })
            .ToListAsync();

        return Ok(list);
    }

    [HttpPost("materials/reading")]
    public async Task<IActionResult> CreateReadingMaterial([FromBody] CreateReadingMaterialRequest request)
    {
        var material = new LearningMaterial
        {
            Title = request.Title.Trim(),
            Description = request.Content.Length > 100 ? request.Content.Substring(0, 100) + "..." : request.Content,
            ContentType = MaterialContentType.Story,
            Level = request.Level,
            LanguageCode = !string.IsNullOrWhiteSpace(request.LanguageCode) ? request.LanguageCode : "en",
            ContentBody = request.Content,
            EstimatedMinutes = request.EstimatedMinutes,
            IsPublished = request.IsPublished,
            CreatedAtUtc = DateTime.UtcNow
        };
        _db.LearningMaterials.Add(material);
        await _db.SaveChangesAsync();
        return Ok(new { success = true, id = material.Id, message = "Reading materiali saqlandi." });
    }

