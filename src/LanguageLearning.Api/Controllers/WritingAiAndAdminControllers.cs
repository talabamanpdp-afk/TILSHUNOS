    [HttpGet("stats")]
    public async Task<IActionResult> GetAdminStats()
    {
        int totalUsers = 0, verifiedUsers = 0, activeTeachers = 0, learnersCount = 0;
        int totalVocab = 0, totalMaterials = 0, totalAssignments = 0, totalSessions = 0, totalAiConversations = 0;
        int readingCount = 0, writingCount = 0, listeningCount = 0, videoCount = 0;

        try
        {
            totalUsers = await _db.Users.CountAsync();
            verifiedUsers = await _db.Users.CountAsync(u => u.EmailConfirmed);
            activeTeachers = await _db.Users.CountAsync(u => u.Role == UserRole.Teacher);
            learnersCount = await _db.Users.CountAsync(u => u.Role == UserRole.Learner);
            totalVocab = await _db.PersonalVocabularyEntries.CountAsync();
            totalMaterials = await _db.LearningMaterials.CountAsync();
            totalAssignments = await _db.Assignments.CountAsync();
            totalSessions = await _db.PracticeSessions.CountAsync();
            totalAiConversations = await _db.AIConversations.CountAsync();
            readingCount = await _db.LearningMaterials.CountAsync(m => m.ContentType == MaterialContentType.Story || m.ContentType == MaterialContentType.News || m.ContentType == MaterialContentType.BookChapter);
            writingCount = await _db.LearningMaterials.CountAsync(m => m.ContentType == MaterialContentType.GrammarLesson);
            listeningCount = await _db.LearningMaterials.CountAsync(m => m.ContentType == MaterialContentType.AudioPodcast);
            videoCount = await _db.LearningMaterials.CountAsync(m => m.ContentType == MaterialContentType.VideoLesson);
        }
        catch
        {
            // Fail-safe defaults
        }

        // Real Level distribution from active learners ONLY (exclude SuperAdmin, Admin, Teacher)
        var learnerUserIds = await _db.Users
            .Where(u => u.Role == UserRole.Learner)
            .Select(u => u.Id)
            .ToListAsync();

        var levels = await _db.UserLearningLanguages
            .Where(l => learnerUserIds.Contains(l.UserId) && l.IsPrimary)
            .GroupBy(l => l.CurrentLevel)
            .Select(g => new { Level = g.Key.ToString(), Count = g.Count() })
            .ToDictionaryAsync(x => x.Level, x => x.Count);

        var a1Count = levels.GetValueOrDefault("A1", 0);
        var a2Count = levels.GetValueOrDefault("A2", 0);
        var b1Count = levels.GetValueOrDefault("B1", 0);
        var b2Count = levels.GetValueOrDefault("B2", 0);
        var c1Count = levels.GetValueOrDefault("C1", 0);
        var c2Count = levels.GetValueOrDefault("C2", 0);

        // If any learner hasn't mapped learning language profile yet, allocate to A1 beginners
        var mappedLearners = a1Count + a2Count + b1Count + b2Count + c1Count + c2Count;
        if (learnersCount > mappedLearners)
        {
            a1Count += (learnersCount - mappedLearners);
        }

        var levelDistribution = new Dictionary<string, int>
        {
            ["A1"] = a1Count,
            ["A2"] = a2Count,
            ["B1"] = b1Count,
            ["B2"] = b2Count,
            ["C1"] = c1Count,
            ["C2"] = c2Count
        };

        // Recent users from Supabase (Super Admin excluded)
        var recentUsers = await _db.Users
            .Where(u => u.NormalizedEmail != "SOXIBGAYBULLAYEV439@GMAIL.COM" && u.Role != UserRole.SuperAdmin)
            .OrderByDescending(u => u.CreatedAtUtc)
            .Take(6)
            .Select(u => new AdminRecentUserDto(
                u.Id,
                u.Email,
                u.FirstName,
                u.LastName,
                u.Role.ToString(),
                u.EmailConfirmed,
                u.IsActive,
                u.CreatedAtUtc
            ))
            .ToListAsync();

        return Ok(new AdminDashboardStatsDto(
            totalUsers,
            verifiedUsers,
            activeTeachers,
            totalVocab,
            totalMaterials,
            totalAssignments,
            totalSessions,
            levelDistribution,
            learnersCount,
            totalAiConversations,
            readingCount,
            writingCount,
            listeningCount,
            videoCount,
            recentUsers
        ));
    }

